// Exercise 2-03: Constants

public class Exercise3 {
    public static void main(String[] args) {

        // Declare a constant for the number of days in a week
        final int DAYS_IN_WEEK = 7;

        // Declare a constant for the number of minutes in an hour
        final int MINUTES_IN_HOUR = 60;

        // Print the constants to the console
        System.out.println("Number of days in a week\t: " + DAYS_IN_WEEK);
        System.out.println("Number of minutes in an hour\t: " + MINUTES_IN_HOUR);
    }
}
